#!/usr/bin/env python3
"""Builds the ahead-of-time guest code image from recordings (BOTWPC_AOT_RECORD, Ryujinx.Cpu AotImage).

usage: aot_build.py <out dir> <recording> [<recording> ...]
       aot_build.py --selftest

Writes <out>/aot_code.bin (dispatch stubs, then every function, 4-byte aligned), <out>/aot_index.bin (sorted entries:
u64 guest address, u64 hash low, u64 hash high, u32 code offset, u32 guest length) and <out>/botw_aot.s, which puts
the code into __TEXT (signed, executable without JIT) and exports _botwpc_aot_code/_entries/_count/_stubs for
botwpc_set_aot_image. The image contains code translated from the game: build it locally, never commit or share it."""
import os
import struct
import sys

FUNC, STUB, SIMD = 0x31464142, 0x31534142, 0x31564142
STUB_KINDS = 6  # dispatch stub, slow dispatch stub, dispatch loop, get/set FP flags, interpreter SIMD trampoline
RET = 0xD65F03C0


def read_recordings(paths):
    functions, stubs, simd = {}, {}, set()
    for path in paths:
        with open(path, "rb") as f:
            data = f.read()
        pos = 0
        while pos + 4 <= len(data):
            (magic,) = struct.unpack_from("<I", data, pos)
            if magic == FUNC:
                if pos + 36 > len(data):
                    break  # truncated tail (recording process killed mid-write)
                addr, glen, hlo, hhi, clen = struct.unpack_from("<QIQQI", data, pos + 4)
                start = pos + 36
                if start + clen > len(data):
                    break
                functions[addr] = (glen, hlo, hhi, data[start:start + clen])
                pos = start + clen
            elif magic == STUB:
                kind, clen = struct.unpack_from("<II", data, pos + 4)
                start = pos + 12
                if start + clen > len(data):
                    break
                stubs[kind] = data[start:start + clen]
                pos = start + clen
            elif magic == SIMD:
                if pos + 8 > len(data):
                    break
                simd.add(struct.unpack_from("<I", data, pos + 4)[0])
                pos += 8
            else:
                raise SystemExit(f"{path}: bad record at offset {pos}")
    return functions, stubs, simd


def build(out, functions, stubs, simd=()):
    code = bytearray()
    stub_offsets = []
    for kind in range(STUB_KINDS):
        if kind in stubs:
            stub_offsets.append(len(code))
            code += stubs[kind]
        else:
            stub_offsets.append(0xFFFFFFFF)
    index = bytearray()
    for addr in sorted(functions):
        glen, hlo, hhi, body = functions[addr]
        offset = len(code)
        code += body
        index += struct.pack("<QQQII", addr, hlo, hhi, offset, glen)
    # Interpreter FP/SIMD stubs: (normalized instruction, RET) pairs sorted by instruction, looked up by binary search.
    simd_offset = len(code)
    for inst in sorted(simd):
        code += struct.pack("<II", inst, RET)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "aot_code.bin"), "wb") as f:
        f.write(code)
    with open(os.path.join(out, "aot_index.bin"), "wb") as f:
        f.write(index)
    stubs_s = ", ".join(str(o) for o in stub_offsets)
    with open(os.path.join(out, "botw_aot.s"), "w") as f:
        f.write(f"""// Generated by aot_build.py: {len(functions)} functions, {len(code) >> 10} KB of code.
.section __TEXT,__botw_aot,regular,pure_instructions
.p2align 14
.globl _botwpc_aot_code
_botwpc_aot_code:
.incbin "{os.path.abspath(os.path.join(out, "aot_code.bin"))}"

.section __TEXT,__const
.p2align 3
.globl _botwpc_aot_entries
_botwpc_aot_entries:
.incbin "{os.path.abspath(os.path.join(out, "aot_index.bin"))}"
.globl _botwpc_aot_count
_botwpc_aot_count:
.long {len(functions)}
.globl _botwpc_aot_stubs
_botwpc_aot_stubs:
.long {stubs_s}
.globl _botwpc_aot_simd_offset
_botwpc_aot_simd_offset:
.long {simd_offset}
.globl _botwpc_aot_simd_count
_botwpc_aot_simd_count:
.long {len(simd)}
""")
    return len(code)


def selftest():
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        rec = os.path.join(d, "r.bin")
        with open(rec, "wb") as f:
            f.write(struct.pack("<IQIQQI", FUNC, 0x8500000, 8, 1, 2, 8) + b"\x40\x05\x80\xd2\xc0\x03\x5f\xd6")
            f.write(struct.pack("<III", STUB, 1, 4) + b"\xc0\x03\x5f\xd6")
            f.write(struct.pack("<IQIQQI", FUNC, 0x8400000, 4, 3, 4, 4) + b"\xc0\x03\x5f\xd6")
            f.write(struct.pack("<IQIQQI", FUNC, 0x8500000, 8, 5, 6, 8) + b"\x60\x05\x80\xd2\xc0\x03\x5f\xd6")  # newer wins
            f.write(struct.pack("<II", SIMD, 0x4E22D420) + struct.pack("<II", SIMD, 0x1E222820) + struct.pack("<II", SIMD, 0x4E22D420))
            f.write(struct.pack("<IQ", FUNC, 1))  # truncated
        fns, stubs, simd = read_recordings([rec])
        assert sorted(fns) == [0x8400000, 0x8500000] and fns[0x8500000][1] == 5 and list(stubs) == [1]
        assert simd == {0x4E22D420, 0x1E222820}
        size = build(d, fns, stubs, simd)
        idx = open(os.path.join(d, "aot_index.bin"), "rb").read()
        e0 = struct.unpack_from("<QQQII", idx, 0)
        e1 = struct.unpack_from("<QQQII", idx, 32)
        assert e0[0] == 0x8400000 and e0[3] == 4 and e1[0] == 0x8500000 and e1[3] == 8 and size == 32
        code = open(os.path.join(d, "aot_code.bin"), "rb").read()
        assert struct.unpack_from("<IIII", code, 16) == (0x1E222820, RET, 0x4E22D420, RET)
        s = open(os.path.join(d, "botw_aot.s")).read()
        assert ".long 4294967295, 0, 4294967295, 4294967295, 4294967295, 4294967295" in s and "_botwpc_aot_count:\n.long 2" in s
        assert "_botwpc_aot_simd_offset:\n.long 16" in s and "_botwpc_aot_simd_count:\n.long 2" in s
    print("selftest ok")


if __name__ == "__main__":
    if sys.argv[1:] == ["--selftest"]:
        selftest()
    elif len(sys.argv) >= 3:
        fns, stubs, simd = read_recordings(sys.argv[2:])
        size = build(sys.argv[1], fns, stubs, simd)
        print(f"{len(fns)} functions, {len(stubs)} stubs, {len(simd)} SIMD stubs, {size >> 20} MB of code -> {sys.argv[1]}/botw_aot.s")
    else:
        sys.exit(__doc__)
